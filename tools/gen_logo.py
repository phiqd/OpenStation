#!/usr/bin/env python3
"""Convert a logo image into src/logo.c (32-colour palette, run-length coded).

    python3 tools/gen_logo.py                 # uses assets/logo.png
    python3 tools/gen_logo.py my_logo.png     # any PNG/JPG; saved as assets/logo.png
    python3 tools/gen_logo.py --default       # redraw the built-in default logo

Two sizes are produced: logo_small for the start-up screen (room for the
handle name underneath) and logo_large for the heater-off screen.

The screen background is black, so dark, uncoloured strokes (black line art)
are turned white; coloured parts keep their colours. A white background is
treated as transparent. Requires Pillow.
"""
import colorsys
import os
import sys
from PIL import Image, ImageDraw, ImageFont

SIZES = {"logo_small": (132, 80), "logo_large": (156, 104)}
ASSET = "assets/logo.png"
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf"
COLOURS = 32


def draw_default():
    """The OpenStation wordmark: 'Open' in white, 'Station' in orange, text only."""
    s = 4
    f = ImageFont.truetype(FONT, 26 * s)
    a, b = "Open", "Station"
    wa, wb = f.getlength(a), f.getlength(b)
    box = f.getbbox(a + b)
    im = Image.new("RGBA", (int(wa + wb) + 8 * s, box[3] + 8 * s), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.text((4 * s, 4 * s), a, font=f, fill=(240, 240, 240))
    d.text((4 * s + wa, 4 * s), b, font=f, fill=(255, 138, 31))
    return im


def to_dark_background(im):
    """RGBA artwork made for a light background -> RGB on black."""
    im = im.convert("RGBA")
    src = im.load()
    w, h = im.size
    # A solid near-white background counts as transparent.
    corners = [src[0, 0], src[w - 1, 0], src[0, h - 1], src[w - 1, h - 1]]
    white_bg = all(c[3] > 200 and min(c[:3]) > 235 for c in corners)
    out = Image.new("RGB", (w, h), (0, 0, 0))
    dst = out.load()
    for y in range(h):
        for x in range(w):
            r, g, b, a = src[x, y]
            if white_bg:
                a = int(a * (255 - min(r, g, b)) / 255) if max(r, g, b) - min(r, g, b) < 40 else a
            if a == 0:
                continue
            hh, ss, vv = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
            if ss < 0.25 and (white_bg or vv < 0.5):   # dark line art -> white
                lv = 1.0 if white_bg else 1.0 - vv
                r = g = b = int(245 * lv)
            k = a / 255
            dst[x, y] = (int(r * k), int(g * k), int(b * k))
    return out


def fit(im, size):
    """Crop to the visible artwork, then scale into size keeping aspect."""
    bbox = im.getbbox()
    if bbox:
        im = im.crop(bbox)
    im = im.copy()
    im.thumbnail(size, Image.LANCZOS)
    return im


def rgb565(c):
    r, g, b = c
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def encode(im):
    q = im.quantize(colors=COLOURS, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:COLOURS * 3]
    pal += [0] * (COLOURS * 3 - len(pal))
    colours = [tuple(pal[i * 3:i * 3 + 3]) for i in range(COLOURS)]
    px = list(q.tobytes())
    dark = min(range(COLOURS), key=lambda i: sum(colours[i]))
    order = [dark] + [i for i in range(COLOURS) if i != dark]
    remap = {old: new for new, old in enumerate(order)}
    colours = [colours[i] for i in order]
    px = [remap[p] for p in px]
    colours[0] = (0, 0, 0)
    # byte = (run - 1) << 5 | colour, runs of 1..8 pixels, row-major
    out, i = [], 0
    while i < len(px):
        c, n = px[i], 1
        while i + n < len(px) and px[i + n] == c and n < 8:
            n += 1
        out.append(((n - 1) << 5) | c)
        i += n
    return colours, out


def main():
    args = sys.argv[1:]
    os.makedirs("assets", exist_ok=True)
    if args and args[0] == "--default":
        src = draw_default()
        src.save(ASSET)
    elif args:
        src = Image.open(args[0])
        src.save(ASSET)
    else:
        if not os.path.exists(ASSET):
            draw_default().save(ASSET)
        src = Image.open(ASSET)
    art = to_dark_background(src)
    lines = ["/* Generated by tools/gen_logo.py from assets/logo.png. Do not edit. */",
             '#include "logo.h"', ""]
    total = 0
    for name, size in SIZES.items():
        im = fit(art, size)
        im.save(f"assets/{name}_preview.png")
        colours, data = encode(im)
        w, h = im.size
        lines.append(f"static const uint16_t {name}_palette[{COLOURS}] = {{")
        for k in range(0, COLOURS, 8):
            lines.append("    " + ", ".join(f"0x{rgb565(c):04x}" for c in colours[k:k + 8]) + ",")
        lines.append("};")
        lines.append(f"static const uint8_t {name}_rle[] = {{")
        for k in range(0, len(data), 20):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[k:k + 20]) + ",")
        lines.append("};")
        lines.append(f"const logo_t {name} = {{{w}, {h}, {name}_palette, {name}_rle, {len(data)}}};")
        lines.append("")
        total += len(data)
        print(f"{name}: {w}x{h}, {len(data)} bytes")
    open("src/logo.c", "w").write("\n".join(lines))
    print(f"total {total} bytes")


if __name__ == "__main__":
    main()

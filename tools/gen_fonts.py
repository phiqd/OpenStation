#!/usr/bin/env python3
"""Generate the anti-aliased fonts used by the UI (src/fonts_aa.c).

16 grey levels (4 bits per pixel) with a slight gamma boost so strokes stay
crisp and full-weight on the ST7735 panel. Requires Pillow and DejaVu Sans
(Bitstream Vera licence, free to embed).
Run from the repository root:  python3 tools/gen_fonts.py
"""
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = "/usr/share/fonts/truetype/dejavu/"
BPP = 4
LEVELS = (1 << BPP) - 1
GAMMA = 0.8          # < 1 thickens anti-aliased edges against a dark background
ASCII = "".join(chr(c) for c in range(32, 127)) + "°"

# name, ttf, pixel size, characters
FONTS = [
    ("font_big", "DejaVuSansCondensed-Bold.ttf", 33, " -0123456789:"),
    ("font_mid", "DejaVuSansCondensed-Bold.ttf", 12, ASCII),
    ("font_small", "DejaVuSansCondensed-Bold.ttf", 10, ASCII),
]


def render(name, ttf, size, chars):
    font = ImageFont.truetype(FONT_DIR + ttf, size)
    top, bottom = 10**6, -10**6
    for ch in chars:
        if ch == " ":
            continue
        box = font.getbbox(ch)
        top, bottom = min(top, box[1]), max(bottom, box[3])
    height = bottom - top
    glyphs = []
    for ch in chars:
        advance = int(round(font.getlength(ch)))
        if ch == " " and name == "font_big":
            advance = int(round(font.getlength("0")))
        img = Image.new("L", (max(advance, 1), height), 0)
        ImageDraw.Draw(img).text((0, -top), ch, fill=255, font=font)
        px = img.load()
        levels = []
        for y in range(height):
            for x in range(advance):
                v = (px[x, y] / 255.0) ** GAMMA
                levels.append(min(LEVELS, int(v * LEVELS + 0.5)))
        glyphs.append((ch, advance, levels))
    return height, glyphs


def pack(levels):
    per_byte = 8 // BPP
    out, acc, n = [], 0, 0
    for lv in levels:
        acc |= lv << (BPP * n)
        n += 1
        if n == per_byte:
            out.append(acc); acc, n = 0, 0
    if n:
        out.append(acc)
    return out


def c_char(ch):
    if ch == "°":
        return "\\260"          # octal: cannot swallow the next character
    if ch in "\\\"":
        return "\\" + ch
    return ch


def main():
    c = ['/* Generated by tools/gen_fonts.py from DejaVu Sans. Do not edit. */',
         '#include "fonts_aa.h"', '']
    h = ['#ifndef FONTS_AA_H', '#define FONTS_AA_H', '', '#include <stdint.h>', '',
         f'#define AA_FONT_BPP {BPP}', '',
         'typedef struct {', '    uint8_t height;', '    uint8_t count;',
         '    const char *chars;          /* glyph order; 0xB0 = degree */',
         '    const uint8_t *widths;', '    const uint16_t *offsets;     /* into data */',
         f'    const uint8_t *data;         /* {BPP} bpp, row-major, LSB first */',
         '} aa_font_t;', '']
    total = 0
    for name, ttf, size, chars in FONTS:
        height, glyphs = render(name, ttf, size, chars)
        data, offsets, widths = [], [], []
        for ch, adv, levels in glyphs:
            offsets.append(len(data)); widths.append(adv); data.extend(pack(levels))
        enc = "".join(c_char(ch) for ch, _, _ in glyphs)
        c.append(f'static const uint8_t {name}_widths[] = {{{", ".join(map(str, widths))}}};')
        c.append(f'static const uint16_t {name}_offsets[] = {{{", ".join(map(str, offsets))}}};')
        c.append(f'static const uint8_t {name}_data[] = {{')
        for i in range(0, len(data), 20):
            c.append('    ' + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ',')
        c.append('};')
        c.append(f'const aa_font_t {name} = {{{height}, {len(glyphs)}, "{enc}", '
                 f'{name}_widths, {name}_offsets, {name}_data}};')
        c.append('')
        h.append(f'extern const aa_font_t {name};   /* {height} px tall, {len(data)} bytes */')
        total += len(data)
        print(f"{name}: height {height}, {len(glyphs)} glyphs, {len(data)} bytes")
    print(f"total glyph data {total} bytes")
    h += ['', '#endif', '']
    open("src/fonts_aa.c", "w").write("\n".join(c))
    open("include/fonts_aa.h", "w").write("\n".join(h))


if __name__ == "__main__":
    main()
